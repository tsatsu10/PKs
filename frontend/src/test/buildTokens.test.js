// @vitest-environment node
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildTokensCss } from '../../scripts/build-tokens.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const realTokens = JSON.parse(readFileSync(join(ROOT, 'design-tokens', 'tokens.json'), 'utf8'));

const tok = (value, type) => ({ $value: value, $type: type, $description: '' });
const sample = () => ({
  core: {
    color: { ink: { 950: tok('#0A0A0F', 'color') }, white: tok('#FFFFFF', 'color') },
    space: { 3: tok('8', 'spacing'), 0: tok('0', 'spacing') },
    radius: { md: tok('10', 'borderRadius') },
    font: { sans: tok(['Plus Jakarta Sans'], 'fontFamilies'), mono: tok(['JetBrains Mono'], 'fontFamilies') },
    text: { size: { body: tok('14', 'fontSizes') }, weight: { bold: tok('700', 'fontWeights') } },
    opacity: { scrim: tok('0.6', 'opacity') },
    size: { icon: { md: tok('20', 'sizing') } },
  },
  'mode/dark': { bg: { app: tok('{color.ink.950}', 'color') } },
  'mode/light': { bg: { app: tok('{color.white}', 'color') } },
  $themes: [],
  $metadata: { tokenSetOrder: ['core', 'mode/dark', 'mode/light'] },
});

/** Custom properties declared inside the first block whose selector matches. */
function block(css, selector) {
  const start = css.indexOf(`${selector} {`);
  if (start < 0) throw new Error(`no block for ${selector}`);
  const body = css.slice(start, css.indexOf('}', start));
  return Object.fromEntries([...body.matchAll(/(--[\w-]+):\s*([^;]+);/g)].map(([, k, v]) => [k, v.trim()]));
}

describe('buildTokensCss', () => {
  const css = buildTokensCss(sample());
  const core = block(css, ':root');
  const dark = block(css, ':root,\n[data-theme="dark"]');
  const light = block(css, '[data-theme="light"]');

  it('marks the file as generated', () => {
    expect(css).toMatch(/Generated by scripts\/build-tokens\.mjs.*do not edit/is);
  });

  it('writes core tokens with the pks prefix and CSS units', () => {
    expect(core).toMatchObject({
      '--pks-color-ink-950': '#0a0a0f',
      '--pks-space-3': '8px',
      '--pks-space-0': '0',
      '--pks-radius-md': '10px',
      '--pks-text-size-body': '0.875rem',
      '--pks-text-weight-bold': '700',
      '--pks-opacity-scrim': '0.6',
      '--pks-size-icon-md': '20px',
    });
  });

  it('quotes font families and adds a generic fallback', () => {
    expect(core['--pks-font-sans']).toBe('"Plus Jakarta Sans", system-ui, sans-serif');
    expect(core['--pks-font-mono']).toBe('"JetBrains Mono", ui-monospace, monospace');
  });

  it('turns references into var() so themes follow the core palette', () => {
    expect(dark['--pks-bg-app']).toBe('var(--pks-color-ink-950)');
    expect(light['--pks-bg-app']).toBe('var(--pks-color-white)');
  });

  it('rejects a reference to a token that does not exist', () => {
    const bad = sample();
    bad['mode/dark'].bg.app = tok('{color.ink.999}', 'color');
    expect(() => buildTokensCss(bad)).toThrow(/color\.ink\.999/);
  });

  it('rejects a token type it does not know how to write', () => {
    const bad = sample();
    bad.core.shadow = { md: tok('0 1px 2px #000', 'boxShadow') };
    expect(() => buildTokensCss(bad)).toThrow(/boxShadow/);
  });

  it('rejects a light token with no dark counterpart', () => {
    const bad = sample();
    bad['mode/light'].bg.sidebar = tok('{color.white}', 'color');
    expect(() => buildTokensCss(bad)).toThrow(/bg\.sidebar/);
  });
});

describe('the committed tokens.css', () => {
  it('matches design-tokens/tokens.json (run npm run tokens after updating it)', () => {
    const committed = readFileSync(join(ROOT, 'src', 'styles', 'tokens.css'), 'utf8').replace(/\r\n/g, '\n');
    expect(committed).toBe(buildTokensCss(realTokens));
  });
});

// WCAG AA (4.5:1) for the design's text tokens on every surface they sit on.
const hex = (v) => [1, 3, 5].map((i) => parseInt(v.slice(i, i + 2), 16));
const lum = (c) => {
  const [r, g, b] = c.map((v) => { v /= 255; return v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4; });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
const ratio = (a, b) => { const [x, y] = [lum(a), lum(b)].sort((m, n) => n - m); return (x + 0.05) / (y + 0.05); };

function resolved(mode) {
  const lookup = (path) => path.split('.').reduce((o, k) => o?.[k], realTokens[mode]) ?? path.split('.').reduce((o, k) => o?.[k], realTokens.core);
  return (path) => {
    let v = lookup(path).$value;
    while (v.startsWith('{')) v = lookup(v.slice(1, -1)).$value;
    return hex(v);
  };
}

describe.each(['mode/dark', 'mode/light'])('design contrast in %s', (mode) => {
  const c = resolved(mode);
  const surfaces = ['bg.app', 'bg.sidebar', 'surface.card', 'surface.sheet', 'surface.raised', 'surface.input'];
  const texts = ['text.primary', 'text.secondary', 'text.muted', 'accent.link', 'status.success', 'status.warning', 'status.danger', 'accent.ai-text'];

  it.each(texts)('%s is at least 4.5:1 on every surface', (text) => {
    const low = surfaces.map((s) => [s, ratio(c(text), c(s))]).filter(([, r]) => r < 4.5);
    expect(low.map(([s, r]) => `${s} ${r.toFixed(2)}`)).toEqual([]);
  });

  it('on-accent text is at least 4.5:1 on both gradient stops', () => {
    expect(ratio(c('text.on-accent'), c('accent.gradient-start'))).toBeGreaterThanOrEqual(4.5);
    expect(ratio(c('text.on-accent'), c('accent.gradient-end'))).toBeGreaterThanOrEqual(4.5);
  });
});
